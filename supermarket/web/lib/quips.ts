export type QuipPlace = keyof typeof QUIPS;

/** הערה למקום נתון. index מאפשר בחירה קבועה (לבדיקות); בלי index נבחרת הערה אקראית. */
export function quip(place: QuipPlace, index?: number): string {
  const options = QUIPS[place];
  const i = index ?? Math.floor(Math.random() * options.length);
  return options[((i % options.length) + options.length) % options.length];
}
